#!/usr/bin/env node
// Attempt to perform MCP discovery via @decaf-ts/mcp-server if available.
// If the package is missing or discovery fails, write a helpful placeholder
// file to .specify/memory/mcp-tools.md explaining the next steps.

import fs from 'fs/promises';
import path from 'path';

const repoRoot = path.resolve(new URL(import.meta.url).pathname, '..', '..', '..');
const outFile = path.join(repoRoot, '.specify', 'memory', 'mcp-tools.md');

async function writePlaceholder(reason) {
  const content = `# MCP Discovery Placeholder

MCP discovery was not executed.

Reason: ${reason}

To run a real MCP discovery, ensure the project has ` + "`@decaf-ts/mcp-server`" + ` installed and available in Node's resolution path. Example:

  npm install --save @decaf-ts/mcp-server

Then run this script again:

  node .specify/scripts/run-mcp-discovery.js

When discovery succeeds, this file will list available MCP tools, versions, and brief descriptions.
`;
  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, content, 'utf8');
  console.log(`Wrote placeholder MCP tools file to ${outFile}`);
}

(async () => {
  try {
    let mcp;
    try {
      // Try dynamic import
      mcp = await import('@decaf-ts/mcp-server');
    } catch (err) {
      await writePlaceholder('`@decaf-ts/mcp-server` not installed or not resolvable');
      process.exit(0);
    }

    // Attempt a few common discovery entrypoints; adapt as the library defines
    if (mcp && typeof mcp.discover === 'function') {
      const result = await mcp.discover();
      const md = `# MCP Discovery Results

Generated by running 

` + "`@decaf-ts/mcp-server.discover()`" + `

Output (JSON):


\`` + `json
${JSON.stringify(result, null, 2)}
\`
`;
      await fs.writeFile(outFile, md, 'utf8');
      console.log(`Wrote MCP discovery results to ${outFile}`);
      process.exit(0);
    }

    // fallback: try to introspect exports
    const exported = Object.keys(mcp).join(', ');
    const md = `# MCP Discovery - Manual Introspection

The installed package '@decaf-ts/mcp-server' was found, but no standard discovery
function named \`discover\` was detected. Available exports: ${exported}

Please consult the package docs and adapt this script to call the appropriate
discovery function. You may also run a manual discovery using the package API.
`;
    await fs.writeFile(outFile, md, 'utf8');
    console.log(`Wrote MCP introspection note to ${outFile}`);
    process.exit(0);
  } catch (err) {
    console.error('Unexpected error while running MCP discovery script:', err);
    await writePlaceholder(String(err));
    process.exit(1);
  }
})();
